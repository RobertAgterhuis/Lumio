/**
 * Generates src/content/help-content.ts from docs/user-manual/{locale}/*.md files.
 * Single source of truth: the docs/ folder is the only place to edit help content.
 *
 * Run:         node scripts/generate-help-content.js
 * Auto-runs:  via "predev" and "prebuild" npm scripts
 */
const fs = require("fs");
const path = require("path");

// ── --help flag ──────────────────────────────────────────────────────────────
if (process.argv.includes("--help") || process.argv.includes("-h")) {
  console.log(`
generate-help-content.js — Embeds markdown help files into a TypeScript module.

USAGE
  node scripts/generate-help-content.js [--help]

OPTIONS
  --help, -h   Show this help message and exit.

PIPELINE
  1. Reads  docs/user-manual/NL/*.md  and  docs/user-manual/EN/*.md
  2. Filters to files matching /^\\d{2}-.*\\.md$/ (numbered chapters only)
  3. Escapes backticks, backslashes and template-literal interpolations
  4. Writes  src/content/help-content.ts  as an embedded record

OUTPUT
  src/content/help-content.ts
    Exports:
      HelpLocale             — "nl" | "en"
      getHelpContent(file, locale) — returns the raw markdown string or undefined

WHEN TO RE-RUN
  Automatically via the "predev" and "prebuild" npm scripts.
  Manually after editing any file in docs/user-manual/.

EXAMPLE
  node scripts/generate-help-content.js
  # → src/content/help-content.ts  (2 locales, NL: 14 files, EN: 14 files)
`);
  process.exit(0);
}

// Root of the monorepo docs folder
const docsDir = path.join(__dirname, "..", "..", "..", "docs", "user-manual");
const outFile = path.join(__dirname, "..", "src", "content", "help-content.ts");

// Map locale code -> subfolder name in docs/user-manual/
const localeMap = {
  nl: "NL",
  en: "EN",
};

// Only include files with a numeric chapter prefix (e.g. 01-aan-de-slag.md)
const CHAPTER_PATTERN = /^\d{2}-.*\.md$/;

const locales = ["nl", "en"];
const content = {};

for (const locale of locales) {
  const dir = path.join(docsDir, localeMap[locale]);

  if (!fs.existsSync(dir)) {
    console.warn(`[generate-help-content] WARNING: Directory not found: ${dir}`);
    content[locale] = {};
    continue;
  }

  const files = fs
    .readdirSync(dir)
    .filter((f) => CHAPTER_PATTERN.test(f))
    .sort();

  content[locale] = {};
  for (const file of files) {
    content[locale][file] = fs.readFileSync(path.join(dir, file), "utf-8");
    console.log(`  [${locale}] ${file}`);
  }
}

// Build TypeScript source
let ts = `/**
 * Auto-generated help content embedded at build time.
 * Source: docs/user-manual/{NL,EN}/*.md
 *
 * DO NOT EDIT MANUALLY - regenerate with: node scripts/generate-help-content.js
 * This file is auto-regenerated by the "predev" and "prebuild" npm scripts.
 */

export type HelpLocale = "nl" | "en";

const helpContent: Record<HelpLocale, Record<string, string>> = {
`;

for (const locale of locales) {
  ts += `  ${locale}: {\n`;
  for (const [file, md] of Object.entries(content[locale])) {
    // Escape for template literal: backticks, backslashes, ${
    const escaped = md
      .replace(/\\/g, "\\\\")
      .replace(/`/g, "\\`")
      .replace(/\$\{/g, "\\${");
    ts += `    "${file}": \`${escaped}\`,\n`;
  }
  ts += `  },\n`;
}

ts += `};

/**
 * Get embedded help markdown content for a chapter file and locale.
 * Returns undefined if not found.
 */
export function getHelpContent(
  filename: string,
  locale: string,
): string | undefined {
  const loc = (locale === "en" ? "en" : "nl") as HelpLocale;
  return helpContent[loc]?.[filename];
}
`;

fs.writeFileSync(outFile, ts, "utf-8");
console.log(`\n✓ Generated ${path.relative(process.cwd(), outFile)}`);
console.log(
  `  ${locales.length} locales, NL: ${Object.keys(content.nl).length} files, EN: ${Object.keys(content.en).length} files`,
);
